// protoc-gen-go-eventbuilders generates New*Event builder functions
// for proto messages that have a "common" field of type Common.
// Generated builders accept Common plus all other required fields as parameters.
package main

import (
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	(protogen.Options{}).Run(func(gen *protogen.Plugin) error { //nolint:exhaustruct_v5 // protogen.Options zero value is intentional
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL) |
			uint64(pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_2023

		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2024
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}

			generateFile(gen, f)
		}

		return nil
	})
}

func generateFile(gen *protogen.Plugin, file *protogen.File) {
	// Find the Common message type in this file
	var commonMsg *protogen.Message

	for _, msg := range file.Messages {
		if msg.GoIdent.GoName == "Common" {
			commonMsg = msg
			break
		}
	}

	if commonMsg == nil {
		return // No Common message in this file
	}

	// Collect messages that have a "common" field of type Common
	type eventInfo struct {
		Msg            *protogen.Message
		RequiredFields []*protogen.Field
	}

	var events []eventInfo

	for _, msg := range file.Messages {
		if msg == commonMsg {
			continue
		}

		var (
			hasCommon      bool
			requiredFields []*protogen.Field
		)

		for _, field := range msg.Fields {
			if field.GoName == "Common" && field.Message == commonMsg {
				hasCommon = true
				continue
			}
			// Check if field has buf.validate.field.required = true
			if isRequiredField(field) {
				requiredFields = append(requiredFields, field)
			}
		}

		if hasCommon {
			events = append(events, eventInfo{Msg: msg, RequiredFields: requiredFields})
		}
	}

	if len(events) == 0 {
		return
	}

	// Generate output file
	filename := file.GeneratedFilenamePrefix + "_eventbuilders.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-go-eventbuilders. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	// Generate builder for each event message
	for _, evt := range events {
		generateEventBuilder(g, evt.Msg, evt.RequiredFields)
	}
}

// isRequiredField checks if field has buf.validate.field.required = true
// by examining the raw proto options for the buf.validate.field extension (number 1159).
func isRequiredField(field *protogen.Field) bool {
	opts := field.Desc.Options()
	if opts == nil {
		return false
	}

	// Get the raw options as a proto message
	optsProto, ok := opts.(*descriptorpb.FieldOptions)
	if !ok {
		return false
	}

	// buf.validate.field extension number is 1159
	// We need to check the unknown fields or use proto reflection
	// to find if required = true is set

	// Use proto reflection to check for the extension
	optsReflect := optsProto.ProtoReflect()

	// Iterate over unknown fields looking for field 1159 (buf.validate.field)
	// The extension is defined as:
	//   extend google.protobuf.FieldOptions {
	//     optional buf.validate.FieldConstraints field = 1159;
	//   }
	// Within FieldConstraints, required is field 25.

	unknownFields := optsReflect.GetUnknown()
	if len(unknownFields) == 0 {
		return false
	}

	// Parse the unknown fields to find field 1159
	// Wire format: varint tag (field_number << 3 | wire_type), then value
	// For an embedded message, wire_type = 2 (length-delimited)
	return parseUnknownForRequired(unknownFields, 1159, 25)
}

// parseUnknownForRequired parses unknown fields looking for a specific extension field
// containing a required=true boolean.
func parseUnknownForRequired(data []byte, extFieldNum, requiredFieldNum int) bool {
	for len(data) > 0 {
		// Read tag (varint)
		tag, n := consumeVarint(data)
		if n <= 0 {
			return false
		}

		data = data[n:]

		fieldNum := int(tag >> 3)
		wireType := int(tag & 0x7)

		if fieldNum == extFieldNum && wireType == 2 {
			// Length-delimited (embedded message)
			length, n := consumeVarint(data)
			if n <= 0 {
				return false
			}

			data = data[n:]

			if int(length) > len(data) {
				return false
			}

			// Parse the embedded message for required field
			embedded := data[:length]
			if parseEmbeddedForRequired(embedded, requiredFieldNum) {
				return true
			}

			data = data[length:]
		} else {
			// Skip this field
			data = skipField(data, wireType)
			if data == nil {
				return false
			}
		}
	}

	return false
}

// parseEmbeddedForRequired looks for a bool field with the given number set to true.
func parseEmbeddedForRequired(data []byte, fieldNum int) bool {
	for len(data) > 0 {
		tag, n := consumeVarint(data)
		if n <= 0 {
			return false
		}

		data = data[n:]

		fNum := int(tag >> 3)
		wireType := int(tag & 0x7)

		if fNum == fieldNum && wireType == 0 {
			// Varint (bool)
			val, n := consumeVarint(data)
			if n <= 0 {
				return false
			}

			return val != 0
		}

		// Skip this field
		data = skipField(data, wireType)
		if data == nil {
			return false
		}
	}

	return false
}

func consumeVarint(data []byte) (uint64, int) {
	var val uint64

	for i := 0; i < len(data) && i < 10; i++ {
		b := data[i]

		val |= uint64(b&0x7F) << (7 * i)
		if b < 0x80 {
			return val, i + 1
		}
	}

	return 0, -1
}

func skipField(data []byte, wireType int) []byte {
	switch wireType {
	case 0: // Varint
		for i := range data {
			if data[i] < 0x80 {
				return data[i+1:]
			}
		}

		return nil
	case 1: // 64-bit
		if len(data) < 8 {
			return nil
		}

		return data[8:]
	case 2: // Length-delimited
		length, n := consumeVarint(data)
		if n <= 0 {
			return nil
		}

		data = data[n:]
		if int(length) > len(data) {
			return nil
		}

		return data[length:]
	case 5: // 32-bit
		if len(data) < 4 {
			return nil
		}

		return data[4:]
	default:
		return nil
	}
}

func generateEventBuilder(g *protogen.GeneratedFile, msg *protogen.Message, requiredFields []*protogen.Field) {
	// Build parameter list: common *Common, then each required field
	params := make([]string, 0, 1+len(requiredFields))

	params = append(params, "common *Common")
	for _, f := range requiredFields {
		params = append(params, toParamName(f.GoName)+" "+goType(f))
	}

	// Build using setter methods (compatible with opaque API in editions)
	g.P("// New", msg.GoIdent.GoName, "Event creates a ", msg.GoIdent.GoName, " with required fields populated.")
	g.P("func New", msg.GoIdent.GoName, "Event(")

	for _, p := range params {
		g.P("\t", p, ",")
	}

	g.P(") *", msg.GoIdent.GoName, " {")
	g.P("\tm := &", msg.GoIdent.GoName, "{}")
	g.P("\tm.SetCommon(common)")

	for _, f := range requiredFields {
		g.P("\tm.Set", f.GoName, "(", toParamName(f.GoName), ")")
	}

	g.P("\treturn m")
	g.P("}")
	g.P()
}

func toParamName(goName string) string {
	// Convert GoName to camelCase parameter: DataSubjectType -> dataSubjectType
	if len(goName) == 0 {
		return goName
	}

	return strings.ToLower(goName[:1]) + goName[1:]
}

func goType(field *protogen.Field) string {
	// Handle message and enum types that need field-specific info
	switch field.Desc.Kind() {
	case protoreflect.MessageKind:
		return "*" + field.Message.GoIdent.GoName
	case protoreflect.EnumKind:
		return field.Enum.GoIdent.GoName
	default:
		return goTypeFromKind(field.Desc.Kind())
	}
}

// goTypeFromKind returns the Go type for scalar protobuf kinds.
func goTypeFromKind(kind protoreflect.Kind) string {
	switch kind {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64"
	case protoreflect.FloatKind:
		return "float32"
	case protoreflect.DoubleKind:
		return "float64"
	case protoreflect.BytesKind:
		return "[]byte"
	default:
		return "interface{}"
	}
}
