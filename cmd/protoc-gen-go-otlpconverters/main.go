// protoc-gen-go-otlpconverters generates ToLogRecord() and FromLogRecord() methods
// for proto messages that have a "common" field of type Common.
// Generated methods convert the event to/from an OTLP plog.LogRecord.
package main

import (
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

// Severity levels for different event types
var warnEvents = map[string]bool{
	"LoginFailed":            true,
	"CMKUnavailable":         true,
	"CMKDisabled":            true,
	"UnauthenticatedRequest": true,
	"UnauthorizedRequest":    true,
}

func main() {
	(protogen.Options{}).Run(func(gen *protogen.Plugin) error { //nolint:exhaustruct_v5 // protogen.Options zero value is intentional
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL) |
			uint64(pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_2023

		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_2024
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}

			generateFile(gen, f)
		}

		return nil
	})
}

// eventInfo holds information about an event message and its fields
type eventInfo struct {
	Msg    *protogen.Message
	Fields []*protogen.Field // All fields except Common
}

func generateFile(gen *protogen.Plugin, file *protogen.File) {
	// Find the Common message type in this file
	var commonMsg *protogen.Message

	for _, msg := range file.Messages {
		if msg.GoIdent.GoName == "Common" {
			commonMsg = msg
			break
		}
	}

	if commonMsg == nil {
		return // No Common message in this file
	}

	// Collect messages that have a "common" field of type Common
	var events []eventInfo

	for _, msg := range file.Messages {
		if msg == commonMsg {
			continue
		}

		var (
			hasCommon bool
			fields    []*protogen.Field
		)

		for _, field := range msg.Fields {
			if field.GoName == "Common" && field.Message == commonMsg {
				hasCommon = true
				continue
			}

			fields = append(fields, field)
		}

		if hasCommon {
			events = append(events, eventInfo{Msg: msg, Fields: fields})
		}
	}

	if len(events) == 0 {
		return
	}

	// Collect all enum types used by event fields for generating parsers
	enumTypes := collectEnumTypes(events)

	// Generate output file
	filename := file.GeneratedFilenamePrefix + "_otlpconverters.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-go-otlpconverters. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	// Generate imports
	g.P("import (")
	g.P(`	"encoding/hex"`)
	g.P(`	"fmt"`)
	g.P(`	"strings"`)
	g.P()
	g.P(`	"go.opentelemetry.io/collector/pdata/pcommon"`)
	g.P(`	"go.opentelemetry.io/collector/pdata/plog"`)
	g.P(`	"google.golang.org/protobuf/types/known/timestamppb"`)
	g.P(")")
	g.P()

	// Generate AuditEvent interface
	g.P("// AuditEvent is implemented by all audit log event types.")
	g.P("type AuditEvent interface {")
	g.P("	GetCommon() *Common")
	g.P("	ToLogRecord() plog.LogRecord")
	g.P("	FromLogRecord(lr plog.LogRecord) error")
	g.P("}")
	g.P()

	// Generate ParseAuditEvent dispatcher
	generateParseAuditEvent(g, events)

	// Generate ToLogRecord and FromLogRecord for each event message
	for _, evt := range events {
		generateToLogRecord(g, evt.Msg, evt.Fields)
		generateFromLogRecord(g, evt.Msg, evt.Fields)
	}

	// Generate helper functions
	generateHelperFunctions(g)

	// Generate enum parsers
	generateEnumParsers(g, enumTypes)
}

// collectEnumTypes returns all unique enum types used by event fields
func collectEnumTypes(events []eventInfo) []*protogen.Enum {
	seen := make(map[protogen.GoIdent]bool)

	var enums []*protogen.Enum

	for _, evt := range events {
		for _, field := range evt.Fields {
			if field.Desc.Kind() == protoreflect.EnumKind {
				ident := field.Enum.GoIdent
				if !seen[ident] {
					seen[ident] = true

					enums = append(enums, field.Enum)
				}
			}
		}
	}

	return enums
}

func generateParseAuditEvent(g *protogen.GeneratedFile, events []eventInfo) {
	g.P("// ParseAuditEvent parses an OTLP LogRecord into the appropriate AuditEvent type.")
	g.P("// It reads the event type from the LogRecord body and dispatches to the correct FromLogRecord method.")
	g.P("func ParseAuditEvent(lr plog.LogRecord) (AuditEvent, error) {")
	g.P("	eventType := lr.Body().Str()")
	g.P("	switch eventType {")

	for _, evt := range events {
		msgName := evt.Msg.GoIdent.GoName
		g.P(`	case "`, msgName, `":`)
		g.P("		e := &", msgName, "{}")
		g.P("		if err := e.FromLogRecord(lr); err != nil {")
		g.P("			return nil, err")
		g.P("		}")
		g.P("		return e, nil")
	}

	g.P("	default:")
	g.P(`		return nil, fmt.Errorf("unknown audit event type: %s", eventType)`)
	g.P("	}")
	g.P("}")
	g.P()
}

func generateToLogRecord(g *protogen.GeneratedFile, msg *protogen.Message, fields []*protogen.Field) {
	msgName := msg.GoIdent.GoName
	severity := "Info"
	severityText := "INFO"

	if warnEvents[msgName] {
		severity = "Warn"
		severityText = "WARN"
	}

	g.P("// ToLogRecord converts ", msgName, " to an OTLP plog.LogRecord.")
	g.P("func (x *", msgName, ") ToLogRecord() plog.LogRecord {")
	g.P("	lr := plog.NewLogRecord()")
	g.P()
	g.P("	if c := x.GetCommon(); c != nil {")
	g.P("		if ts := c.GetTimestamp(); ts != nil {")
	g.P("			lr.SetTimestamp(pcommon.Timestamp(ts.AsTime().UnixNano()))")
	g.P("		}")
	g.P("		if c.HasTraceId() {")
	g.P("			if tid, err := parseTraceID(c.GetTraceId()); err == nil {")
	g.P("				lr.SetTraceID(tid)")
	g.P("			}")
	g.P("		}")
	g.P("		if c.HasSpanId() {")
	g.P("			if sid, err := parseSpanID(c.GetSpanId()); err == nil {")
	g.P("				lr.SetSpanID(sid)")
	g.P("			}")
	g.P("		}")
	g.P("		for k, v := range c.GetProperties() {")
	g.P(`			lr.Attributes().PutStr("common.properties."+k, v)`)
	g.P("		}")
	g.P("	}")
	g.P()
	g.P(`	lr.Body().SetStr("`, msgName, `")`)
	g.P("	lr.SetSeverityNumber(plog.SeverityNumber", severity, ")")
	g.P(`	lr.SetSeverityText("`, severityText, `")`)
	g.P()

	// Add event-specific attributes
	for _, field := range fields {
		attrName := toSnakeCase(field.GoName)
		switch field.Desc.Kind() {
		case protoreflect.StringKind:
			g.P(`	lr.Attributes().PutStr("`, attrName, `", x.Get`, field.GoName, `())`)
		case protoreflect.BoolKind:
			g.P(`	lr.Attributes().PutBool("`, attrName, `", x.Get`, field.GoName, `())`)
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
			protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
			g.P(`	lr.Attributes().PutInt("`, attrName, `", int64(x.Get`, field.GoName, `()))`)
		case protoreflect.Uint32Kind, protoreflect.Fixed32Kind,
			protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
			g.P(`	lr.Attributes().PutInt("`, attrName, `", int64(x.Get`, field.GoName, `()))`)
		case protoreflect.FloatKind, protoreflect.DoubleKind:
			g.P(`	lr.Attributes().PutDouble("`, attrName, `", float64(x.Get`, field.GoName, `()))`)
		case protoreflect.EnumKind:
			g.P(`	lr.Attributes().PutStr("`, attrName, `", x.Get`, field.GoName, `().String())`)
		case protoreflect.BytesKind:
			g.P(`	lr.Attributes().PutStr("`, attrName, `", hex.EncodeToString(x.Get`, field.GoName, `()))`)
		case protoreflect.MessageKind:
			// Skip nested messages for now - could be extended to handle specific types
			g.P(`	// TODO: handle nested message field `, field.GoName)
		default:
			g.P(`	// Unsupported field type for `, field.GoName)
		}
	}

	g.P()
	g.P("	return lr")
	g.P("}")
	g.P()
}

func generateFromLogRecord(g *protogen.GeneratedFile, msg *protogen.Message, fields []*protogen.Field) {
	msgName := msg.GoIdent.GoName

	g.P("// FromLogRecord populates ", msgName, " from an OTLP plog.LogRecord.")
	g.P("func (x *", msgName, ") FromLogRecord(lr plog.LogRecord) error {")
	g.P("	// Parse common fields")
	g.P("	c := &Common{}")
	g.P("	c.SetTimestamp(timestamppb.New(lr.Timestamp().AsTime()))")
	g.P("	if !lr.TraceID().IsEmpty() {")
	g.P("		c.SetTraceId(formatTraceID(lr.TraceID()))")
	g.P("	}")
	g.P("	if !lr.SpanID().IsEmpty() {")
	g.P("		c.SetSpanId(formatSpanID(lr.SpanID()))")
	g.P("	}")
	g.P()
	g.P("	// Parse properties from attributes with common.properties. prefix")
	g.P("	props := make(map[string]string)")
	g.P("	lr.Attributes().Range(func(k string, v pcommon.Value) bool {")
	g.P(`		if propKey, ok := strings.CutPrefix(k, "common.properties."); ok {`)
	g.P("			props[propKey] = v.Str()")
	g.P("		}")
	g.P("		return true")
	g.P("	})")
	g.P("	if len(props) > 0 {")
	g.P("		c.SetProperties(props)")
	g.P("	}")
	g.P("	x.SetCommon(c)")
	g.P()

	// Parse event-specific fields
	g.P("	// Parse event-specific fields")

	for _, field := range fields {
		attrName := toSnakeCase(field.GoName)
		switch field.Desc.Kind() {
		case protoreflect.StringKind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(v.Str())")
			g.P("	}")
		case protoreflect.BoolKind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(v.Bool())")
			g.P("	}")
		case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(int32(v.Int()))")
			g.P("	}")
		case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(v.Int())")
			g.P("	}")
		case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(uint32(v.Int()))")
			g.P("	}")
		case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(uint64(v.Int()))")
			g.P("	}")
		case protoreflect.FloatKind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(float32(v.Double()))")
			g.P("	}")
		case protoreflect.DoubleKind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(v.Double())")
			g.P("	}")
		case protoreflect.EnumKind:
			enumName := field.Enum.GoIdent.GoName

			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		x.Set", field.GoName, "(parse", enumName, "(v.Str()))")
			g.P("	}")
		case protoreflect.BytesKind:
			g.P(`	if v, ok := lr.Attributes().Get("`, attrName, `"); ok {`)
			g.P("		if b, err := hex.DecodeString(v.Str()); err == nil {")
			g.P("			x.Set", field.GoName, "(b)")
			g.P("		}")
			g.P("	}")
		case protoreflect.MessageKind:
			// Skip nested messages for now
			g.P(`	// TODO: handle nested message field `, field.GoName)
		default:
			g.P(`	// Unsupported field type for `, field.GoName)
		}
	}

	g.P()
	g.P("	return nil")
	g.P("}")
	g.P()
}

func generateHelperFunctions(g *protogen.GeneratedFile) {
	g.P("// parseTraceID converts a 32-character hex string to a pcommon.TraceID.")
	g.P("func parseTraceID(s string) (pcommon.TraceID, error) {")
	g.P("	var tid pcommon.TraceID")
	g.P("	b, err := hex.DecodeString(s)")
	g.P("	if err != nil {")
	g.P("		return tid, err")
	g.P("	}")
	g.P("	if len(b) != 16 {")
	g.P("		return tid, hex.ErrLength")
	g.P("	}")
	g.P("	copy(tid[:], b)")
	g.P("	return tid, nil")
	g.P("}")
	g.P()
	g.P("// parseSpanID converts a 16-character hex string to a pcommon.SpanID.")
	g.P("func parseSpanID(s string) (pcommon.SpanID, error) {")
	g.P("	var sid pcommon.SpanID")
	g.P("	b, err := hex.DecodeString(s)")
	g.P("	if err != nil {")
	g.P("		return sid, err")
	g.P("	}")
	g.P("	if len(b) != 8 {")
	g.P("		return sid, hex.ErrLength")
	g.P("	}")
	g.P("	copy(sid[:], b)")
	g.P("	return sid, nil")
	g.P("}")
	g.P()
	g.P("// formatTraceID converts a pcommon.TraceID to a 32-character hex string.")
	g.P("func formatTraceID(tid pcommon.TraceID) string {")
	g.P("	return hex.EncodeToString(tid[:])")
	g.P("}")
	g.P()
	g.P("// formatSpanID converts a pcommon.SpanID to a 16-character hex string.")
	g.P("func formatSpanID(sid pcommon.SpanID) string {")
	g.P("	return hex.EncodeToString(sid[:])")
	g.P("}")
}

func generateEnumParsers(g *protogen.GeneratedFile, enums []*protogen.Enum) {
	for _, enum := range enums {
		enumName := enum.GoIdent.GoName

		g.P()
		g.P("// parse", enumName, " converts a string to ", enumName, ".")
		g.P("func parse", enumName, "(s string) ", enumName, " {")
		g.P("	if v, ok := ", enumName, "_value[s]; ok {")
		g.P("		return ", enumName, "(v)")
		g.P("	}")
		g.P("	return 0")
		g.P("}")
	}
}

// toSnakeCase converts GoName to snake_case for attribute names
func toSnakeCase(s string) string {
	var result strings.Builder

	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			result.WriteByte('_')
		}

		if r >= 'A' && r <= 'Z' {
			result.WriteByte(byte(r - 'A' + 'a'))
		} else {
			result.WriteRune(r)
		}
	}

	return result.String()
}
